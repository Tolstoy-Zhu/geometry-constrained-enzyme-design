"""Parse and filter Foldseek result tables."""
from __future__ import annotations

import re
from pathlib import Path
from typing import List, Optional, Tuple

import pandas as pd

from .foldseek_runner import FOLDSEEK_FIELDS

NUMERIC_COLUMNS = [
    "evalue", "bits", "prob", "alntmscore", "qtmscore", "ttmscore",
    "rmsd", "fident", "alnlen", "qlen", "tlen", "qcov", "tcov",
]


def load_foldseek_tsv(path: str | Path, fields: Optional[List[str]] = None) -> pd.DataFrame:
    """Load Foldseek TSV.

    Foldseek output generated by this project has no header, so we assign the
    columns defined in FOLDSEEK_FIELDS. If you already have a header, the code
    tries to detect it automatically.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(path)

    expected_fields = list(fields or FOLDSEEK_FIELDS)

    first_data_line = ""
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip() and not line.startswith("#"):
                first_data_line = line.rstrip("\r\n")
                break
    observed_columns = len(first_data_line.split("\t")) if first_data_line else 0
    if observed_columns and observed_columns != len(expected_fields):
        if observed_columns < len(expected_fields):
            expected_fields = expected_fields[:observed_columns]
        else:
            expected_fields.extend(
                f"extra_field_{index}"
                for index in range(len(expected_fields) + 1, observed_columns + 1)
            )

    # Try headerless first.
    df = pd.read_csv(path, sep="\t", names=expected_fields, comment="#")

    # If first row seems to be a header, reload with header.
    if len(df) > 0 and str(df.iloc[0]["query"]).lower() == "query":
        df = pd.read_csv(path, sep="\t", comment="#")

    for col in NUMERIC_COLUMNS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def parse_pdb_chain(target_id: str) -> Tuple[Optional[str], Optional[str]]:
    """Parse PDB ID and chain from a target identifier.

    Supported examples:
    - 7wwf-A
    - 7wwf_A
    - 7WWF
    - pdb|7wwf|A
    """
    s = str(target_id).strip()

    # pdb|7wwf|A style.
    m = re.search(r"(?:^|\|)([0-9][A-Za-z0-9]{3})\|([A-Za-z0-9]+)(?:\||$)", s)
    if m:
        return m.group(1).upper(), m.group(2)

    # 7wwf_chain_A, 7wwf-A, and 7wwf_A embedded in longer IDs.
    m = re.search(
        r"([0-9][A-Za-z0-9]{3})(?:[-_](?:chain[-_])?([A-Za-z0-9]+))?",
        s,
        flags=re.IGNORECASE,
    )
    if m:
        return m.group(1).upper(), m.group(2)

    return None, None


def parse_uniprot_from_afdb(target_id: str) -> Optional[str]:
    """Parse UniProt accession from AlphaFold DB style target IDs.

    Examples:
    - AF-P12345-F1-model_v4 -> P12345
    - AF-A0A1234567-F1-model_v4 -> A0A1234567
    """
    return parse_uniprot_accession(target_id)


def parse_uniprot_accession(target_id: str) -> Optional[str]:
    """Parse a UniProt accession from common Foldseek target identifiers."""
    s = str(target_id).strip()

    # AlphaFold DB style: AF-P12345-F1-model_v4.
    m = re.search(r"\bAF-([A-Z0-9]+)-F\d+", s)
    if m:
        return m.group(1)

    # UniProt FASTA styles: sp|P12345|NAME or tr|A0A1234567|NAME.
    m = re.search(r"\b(?:sp|tr)\|([A-Z0-9]+)\|", s, flags=re.IGNORECASE)
    if m:
        return m.group(1)

    # UniRef styles often retain the seed accession after the prefix.
    m = re.search(r"\bUniRef(?:50|90|100)_([A-Z0-9]+)\b", s, flags=re.IGNORECASE)
    if m:
        return m.group(1)

    # Canonical 6- or 10-character UniProt accessions. This intentionally
    # starts with a letter, so PDB IDs such as 7WWF are not matched.
    m = re.search(r"\b([OPQ][0-9][A-Z0-9]{3}[0-9]|[A-NR-Z][0-9][A-Z][A-Z0-9]{2}[0-9]|A0A[A-Z0-9]{7})\b", s)
    if m:
        return m.group(1)
    return None


def parse_ncbi_protein_accession(target_id: str) -> Optional[str]:
    """Parse a GenBank/RefSeq protein accession from a Foldseek target ID."""
    s = str(target_id).strip()

    # NCBI pipe styles: ref|WP_012345678.1|, gb|ABC12345.1|, emb|CAA12345.1|.
    m = re.search(r"\b(?:ref|gb|emb|dbj|pir|prf)\|([^|]+)\|", s, flags=re.IGNORECASE)
    if m:
        return m.group(1)

    # RefSeq proteins such as WP_, NP_, XP_, YP_ and ZP_.
    m = re.search(r"\b([A-Z]{2}_[0-9]+(?:\.[0-9]+)?)\b", s)
    if m:
        return m.group(1)

    # GenBank protein accessions, broad enough for modern WGS prefixes.
    m = re.search(r"\b([A-Z]{3,4}[0-9]{5,9}(?:\.[0-9]+)?)\b", s)
    if m:
        return m.group(1)
    return None


def filter_hits(
    df: pd.DataFrame,
    min_alntmscore: float = 0.45,
    max_rmsd: float = 4.0,
    min_qcov: float = 0.60,
    min_tcov: float = 0.40,
    min_alnlen: int = 180,
    max_sequence_identity: float = 0.95,
) -> pd.DataFrame:
    """Filter hits by structural similarity and remove near-identical hits."""
    out = df.copy()

    if "alntmscore" in out.columns:
        out = out[out["alntmscore"].fillna(0) >= min_alntmscore]
    if "rmsd" in out.columns:
        out = out[out["rmsd"].fillna(999) <= max_rmsd]
    if "qcov" in out.columns:
        out = out[out["qcov"].fillna(0) >= min_qcov]
    if "tcov" in out.columns:
        out = out[out["tcov"].fillna(0) >= min_tcov]
    if "alnlen" in out.columns:
        out = out[out["alnlen"].fillna(0) >= min_alnlen]
    if "fident" in out.columns:
        out = out[out["fident"].fillna(0) <= max_sequence_identity]

    sort_cols = [c for c in ["alntmscore", "qcov", "tcov", "bits"] if c in out.columns]
    if sort_cols:
        out = out.sort_values(sort_cols, ascending=[False] * len(sort_cols))

    out = out.reset_index(drop=True)
    out.insert(0, "rank_after_filter", range(1, len(out) + 1))
    return out
